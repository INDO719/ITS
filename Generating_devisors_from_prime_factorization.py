from math import prod
from itertools import permutations


def f(n: int) -> list:
    """
    Раскладывает натуральное число на простые множители.

    Рекурсивно делит число на наименьший найденный делитель до тех пор,
    пока не останется простое число.

    Args:
        n: Натуральное число (n >= 1), которое нужно разложить на множители.

    Returns:
        Список простых множителей числа n с учётом кратности.
        Для n == 1 возвращается пустой список.

    Examples:
        >>> f(12)
        [3, 2, 2]
        >>> f(7)
        [7]
        >>> f(1)
        []
    """

    if n == 1: return []
    for i in range(2, int(n ** 0.5) + 1):
        if n % i == 0:
            return f(n // i) + [i]
    return [n]


def div(simple_numbers: list) -> list:
    """
    Возвращает список всех натуральных делителей числа по его разложению.

    Для каждой непустой перестановки (с учётом кратности) элементов входного
    списка вычисляется произведение, которое добавляется в результирующее
    множество — это позволяет избавиться от дубликатов. В конце к результату
    добавляется 1.

    Args:
        simple_numbers: Список простых множителей числа с учётом кратности,
            например, результат работы функции ``f``.

    Returns:
        Список всех натуральных делителей числа, включая 1.
        Порядок элементов не гарантирован.

    Examples:
        >>> sorted(div(f(12)))
        [1, 2, 3, 4, 6, 12]
        >>> sorted(div(f(7)))
        [1, 7]
    """

    result = set()

    for x in range(len(simple_numbers)):
        list_of_variation = [prod(y) for y in permutations(simple_numbers, r=x + 1)]
        for i in list_of_variation:
            result.add(i)
    return [1] + list(result)

